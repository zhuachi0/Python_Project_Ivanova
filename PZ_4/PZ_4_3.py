# Ввести 4 числа. Найти и вывести на экран сумму и количество отрицательных чисел.

otr = 0
summa = 0
i = 1

while i <= 4:
    n = int(input(f'Введите {i}-е число: '))
    
    if n < 0:
        otr += 1
        summa += n
        
    i += 1

print(f'Количество отрицательных чисел: {otr}, их сумма: {summa}')
