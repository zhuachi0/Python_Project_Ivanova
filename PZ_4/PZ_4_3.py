# Ввести 4 числа. Найти и вывести на экран сумму и количество отрицательных чисел.

n1 = int(input('Введите первое число: '))
n2 = int(input('Введите второе число: '))
n3 = int(input('Введите третье число: '))
n4 = int(input('Введите четвертое число: '))

otr = 0
summa = 0
for i in (n1, n2, n3, n4):
    if i < 0:
        otr += 1
        summa += i
print(f'Количество отрицательных чисел: {otr}, их сумма: {summa}')
