# Даны два целых числа A и B (A < B). Найти сумму всех целых чисел от A до B включительно (использовать оператор цикла).

a = int(input('Введите первое число: '))
b = int(input('Введите второе число: '))
summa = 0
i = a

while i <= b:
    summa += i

    i += 1
    
print(f'Сумма чисел: {summa}') 
    