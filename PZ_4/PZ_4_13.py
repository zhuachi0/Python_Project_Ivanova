# Дана арифметическая прогрессия a1=1, a2=4, a3=7, a4=10, a5=13, ... 
# Составить программу, которая каждый элемент прогрессии разделит на 2 и результат округлит до ближайшего целого.

a1 = 1
d = 3
n = int(input('Введите количество членов прогрессии: '))
i = 1

while i <= n:
    delen = a1 / 2
    res = round(delen)
    print(res, end=' ')
    a1 += d
    
    i += 1