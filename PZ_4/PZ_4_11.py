# Посчитать и вывести количество элементов арифметической прогрессии, удовлетворяющих условию 10 < a_i < 30.

a1 = int(input('Введите первый член прогрессии: '))
d = int(input('Введите шаг прогрессии: '))
n = int(input('Введите количество членов прогрессии: '))
kol = 0

for i in range(1, n + 1):
    ai = a1 + d * (i - 1)
    if 10 < ai < 30:
        kol += 1
print(f'Количество элементов: {kol}')