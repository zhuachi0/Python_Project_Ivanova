# Ввести N чисел. Посчитать и вывести количество чисел равных нулю.

kol = int(input('Введите количество чисел: '))
summa = 0
i = 1

while i <= kol:
    n = int(input(f'Введите {i}-е число: '))
    if n == 0:
        summa += 1

    i += 1
    
print(f'Количество чисел: {kol} \nИз них нулей: {summa}')