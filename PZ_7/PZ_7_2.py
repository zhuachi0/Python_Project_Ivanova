# Дана строка-предложение на русском языке. Вывести самое длинное слово в предложении. 
# Если таких слов несколько, то вывести первое из них. Словом считать набор символов, не содержащий пробелов, 
# знаков препинания и ограниченный пробелами, знаками препинания или началом/концом строки.

stroka = input('Введите предложение: ')

word = stroka.split()
slovo = ''
max_dlina = 0

for i in word:
    if len(i) > max_dlina:
        max_dlina = len(i)
        slovo = i

print(slovo)        
