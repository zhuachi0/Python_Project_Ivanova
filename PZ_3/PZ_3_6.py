# Дано целое число. Если оно является положительным,
# то прибавить к нему 20, в противном случае вычесть из него 5.

n = input('Введите число: ')

while type(n) != int:
    try:
        n = int(n)
    except ValueError:
        print('Нужно ввести целое число')
        n = input('Введите число: ')

if n > 0:
    pol = n + 20
    print(f'Число положительное. Результат действия: {pol}')
else:
    otr = n - 5
    print(f'Число отрицательное. Результат действия: {otr}')